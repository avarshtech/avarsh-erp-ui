/**
 * Get hex color for a color name
 * @param {string} colorName - Color name
 * @returns {string|null} Hex color or null
 */
export const getColorHex = (colorName) => {
  if (!colorName) return null;
  const key = colorName.toLowerCase().trim();
  return COLOR_HEX_MAP[key] || null;
};

/**
 * Find color object from palette by name
 * @param {string} colorName - Color name
 * @returns {Object|null} Color object or null
 */
export const findColorByName = (colorName) => {
  if (!colorName) return null;
  return COLOR_PALETTE.find(
    (c) => c.name.toLowerCase() === colorName.toLowerCase()
  ) || null;
};

